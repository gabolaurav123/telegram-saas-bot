def normalize_language(language: str | None, supported_languages: Iterable[str] | None = None) -> str:
    supported = {item.lower().strip() for item in (supported_languages or _TRANSLATIONS) if item}
    if not supported:
        supported = {DEFAULT_LANGUAGE}
    code = (language or DEFAULT_LANGUAGE).lower().strip().split("-")[0]
    if code in supported and code in _TRANSLATIONS:
        return code
    return DEFAULT_LANGUAGE if DEFAULT_LANGUAGE in supported else sorted(supported)[0]


def t(language: str | None, key: str, **kwargs: object) -> str:
    lang = normalize_language(language)
    template = _TRANSLATIONS.get(lang, {}).get(key) or _TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    return template.format(**kwargs) if kwargs else template
